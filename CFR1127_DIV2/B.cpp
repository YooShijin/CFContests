ll square(ll x)
{
    int sum = 0;
    while (x)
    {
        int d = x % 10;
        sum += (d * d);
        x = x / 10;
    }

    return sum;
}
void solve()
{
    ll n;
    cin >> n;
    vll a(n, 0);
    for (auto &i : a)
    {
        cin >> i;
    }
    ll hue = *max_element(a.begin(), a.end());
    vll b = a;

    ll sum = a[0];
    for (int i = 1; i < n; i++)
    {
        hue = max({hue, a[i] + sum, a[i] - sum});
        a[i] = min({a[i], a[i] - sum, a[i] + sum});
        sum += a[i];
    }
    ll ssum = b[0];
    for (int i = 1; i < n; i++)
    {
        hue = max({hue, b[i] + ssum, b[i] - ssum});
        b[i] = max({b[i], b[i] - ssum, b[i] + ssum});
        ssum += b[i];
    }
    cout << hue << endl;
}

